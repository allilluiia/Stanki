function createMachine(input: {
  slug: string;
  model: string;
  categoryId: CategoryId;
  name: string;
  shortDescription?: string;
  application?: string;
  capabilities?: string[];
  standardEquipment?: string[];
  options?: string[];
  heroMetrics?: MachineMetric[];
  specs?: SpecRow[];
  compare?: MachineCompare;
  source?: string;
  heroImage?: string;
}): Machine {
  return {
    brand: "SZGH",
    heroMetrics: input.heroMetrics ?? [],
    specs: input.specs ?? [],
    compare: input.compare ?? {},
    capabilities: input.capabilities ?? [],
    standardEquipment: input.standardEquipment ?? [],
    options: input.options ?? [],
    documents: documentSlots(input.model),
    dataStatus: input.specs && input.specs.length > 0 ? "verified" : "draft",
    media: {
      hero: input.heroImage || machineHeroUrl(),
    },
    slug: input.slug,
    model: input.model,
    categoryId: input.categoryId,
    name: input.name,
    shortDescription: input.shortDescription,
    application: input.application,
    source: input.source,
    updatedAt: "2026-10-19",
  };
}

